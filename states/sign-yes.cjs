// 举✅牌：她点名「一定想要」的那一对里的「好」。参考是 ref-7 第二格——右手举一面绿底白勾的圆牌，眨一只眼、笑着。
// 那一格靠什么读出来：脸边一块绿圆牌 + 牌上一个白勾 + 一只眼闭着一只睁着 + 另一只手也举起来。小家伙没有嘴，「笑」押在四样大剪影上：
//   ① 牌子：11 格的圆（直径 55）、ink 描一圈边、signGreen 底、earWhite 白勾，柄 leatherLight 5×15 从手顶往上接到牌底正中。
//      ink 边是给白底聊天、纸色浅底看的；深底 #0d1430 上边看不见，剩下的绿圆和白勾照样是一块牌。
//      [1015 复审] 绿原来用 19 色里现成的 green（#709777，饱和度 0.26），70pt 下是一块灰绿，和 ❌ 那块鲜红（0.63）摆在一起，
//      「好」那一面显得发蔫。这一支补一个 signGreen #3f9a4e：饱和度 0.59 和红对上，深底上对比 5.1、纸上 2.6，白勾压在上面 3.5（原来 3.3），
//      两块牌摆一起一红一绿一样亮。只进这一支的色表，不进 manifest 的 palette。
//   ② 勾：没直接用 ctx.shapes.check（5×5 格、25×25）——缩到 70pt 只有 6 个点宽，笔画一格 1.2pt 糊成一团；
//      这里画 7×6 格（35×30）、两格粗的「✔」，在牌面里左右各让一格、上让两格下让一格（勾的分量在左下）。
//   ③ 眨眼：左眼（离牌子远的那只，ref-7 也是这只）闭着，右眼睁着平视她。参考里是一道往上弯的笑眼：
//      [1015 复审] 原来就是 closed 那一道平线，像「闭一只眼」不像「笑着眨眼」；现在闭着的那只两头各往下补一格 ink，
//      成大笑、尴尬流汗里同一个「∩」（effects 层，跟着 ctx.eyes[0].drawn 走）。身子压扁、脚会落进马甲那一行的帧（39）不补，只剩那一道。
//   ④ 另一只手：ref-7 里空着的那只胳膊也举着，像在喊「耶」。左手往外上抬 10、歪 −15°（挥手那只手的角度），举牌的那几帧一直举着。
//
// 牌子为什么举在帽子右上、不在脸边（ref-7 是贴着脸）：
//   贴到脸边（y 170–230）的话牌面左边那 20 列正好落在帽子框里：礼帽檐尖 210–220×201–208、睡帽的绒球 210–230×188–208、
//   风雪帽的毛兜到 220、一直垂到 243——props 层在帽子层上头，换哪套衣服都是一块绿牌压着帽边。
//   所以手举到帽檐右头外面，牌面整块在帽顶右上。
//   [1015 复审] 原来手画在 225–245×190–210，正贴着檐右头外侧——可睡帽的绒球吊在帽框 x 130–150（待机画面 210–230×188–208），
//   举着的手盖掉绒球右边 5 列，晃到左边那几下盖掉一半，30 / 48pt 下手、柄、绒球糊成一团。现在举着的手往右让 5、往上提 5，
//   画在 230–250×185–205：左边正好贴着绒球的右缘、一个像素都不压，离礼帽的檐尖 10；牌面跟着到 215–270×115–170，
//   四套帽子在 y 170 以上都不过 x 205，牌一个像素都碰不到（verify 每帧穿四套衣服量）。
//   离身子右缘 20，比规矩里「最远 15」多一格（指路那只是 20）：举牌的手和帽檐、柄、牌连成一个东西，看着是从帽檐边上举起来的，不是飘着的一粒。
//
// 垂下来为什么藏到帽子后面（paper 层）、而且往外斜一格：
//   直径 55 的牌加 15 的柄，胳膊垂到底（手画在 243–263，和身子底边齐）牌面也还在 173–228——就在他耳朵边上，
//   这时候画在前面一定压着檐尖、睡帽绒球、风雪帽的毛边。真人拿着棒棒糖似的牌子垂下手，牌也就是靠在身侧、半挡在脑袋后面，
//   所以垂着的那几帧柄、牌、勾三样都画在最底的 paper 层：帽子和身子自然挡住靠里的那一圈。
//   [1015 复审] 原来垂下来是直的（牌面 210–265），睡帽的绒球正落在白勾左上角，米色压白色连成一大块，勾认不出来。
//   现在垂着的牌往外斜一格（柄斜成一道台阶、牌面往右 10，和 ❌ 摇牌同一个画法）：牌面 220–275，勾在 230 以外，
//   绒球只搭在牌的左边沿上（米色压在绿和黑边上，两样都看得清）；礼帽、风雪帽到 220 为止，正好挨着牌边。
//   一举起来再回到 props 层（勾在 lettering 层，牌子上的记号照 README 的规矩放那儿）。
//
// 星为什么在牌子左上、帽子和牌中间（175–200×120–145）：放牌子右边就出了 265，整支的外框会宽一截（贴纸裁框按所有帧的外框量）；
// 放牌子正上方，蹦到顶的那一帧牌面顶到 100，正好撞上。左上这块，蹦起来也离牌面 15、离帽顶三行以上，四套帽子都碰不到。
//
// 和 sign-no（举❌牌）是一对：同一个柄、同一块 11 格的圆、同一组手位（举着 x 220 / y 180，放到半路 213、垂 238、预备 243 时 x 215）
// 和同一套「垂着往外斜一格、藏到帽后」，
// 两张摆在一起，牌子在同一个地方，只有颜色、记号、眼神不一样。
//
// 节拍（45 帧，70/60/70ms，一圈 3 秒）：
//   0–3    举着停住：右上绿牌、左眼眨着、左手「耶」；0–1 金星大的、2–3 缩成小十字星。首帧就是静图，也就是表情包那一帧
//   4–16   晃两下：身子 +5 / −5 / +5 / −5 / 回正，挪的那一帧拉长 5、帽子落后一帧（往右挪帽子留在左边 5，反过来也是）；
//          往左那两下牌子在下一帧随势往左斜一格（柄斜成台阶、牌面往左 10，手不动）——原来是手跟着多挪 5，手一挪就压到睡帽绒球上；
//          不放在挪的那一帧：那一帧帽子还落在右边（verify 第一回就在第 7、13 帧抓到过擦边）
//   17–19  停住，还眨着；20–21 睁开两只眼看她
//   22     一帧放到半路（手回到身侧那么高），牌子转到帽子后面
//   23     垂到底（手 243–263，牌面往外斜一格到 220–275 × 173–228，靠里那一圈藏在帽檐后），身子压 5，像牌子有分量；24 回弹
//   25–32  垂着歇；26–29 往右瞟一眼自己的牌；31–32 眨眼（31 是 45 帧里老动作没用过的起点）
//   33–34  预备：压 5、手再往下沉 5，抬眼往右上看——牌要去的地方
//   35     一帧举到位：手跨 68（全片最大的一步），身子拉长 5，眼睛还往右上看着牌
//   36–40  牌到位弹一下：36 离地 10、冒一颗小星、两只眼都笑眯成「∩」；37 顶点离地 20、星长成大的；38 落到 10（帽子浮起 5），又是左眼眨着、右眼睁着；
//          [1015 复审] 36–37 原来是一睁一闭，睁着那只眼只让帽檐沉 4，收尾自动算的落后被夹成 4、帽子两帧落在 5 格外；两只都眯起来就让得出 5
//          39 落地压 10，牌跟着沉 10；40 压 5
//   41–44  和首帧整张一样（星也是大的），接缝为零
const HX = 220, UP = 180;                              // 举着的右手姿势：画出来 230–250 × 185–205，贴着睡帽绒球右缘、离礼帽檐尖 10
const HX_LOW = 215, MID = 213, REST = 238, DIP = 243;  // 放到半路 / 垂到底 / 预备再沉 5 的右手姿势（画出来 225–245，引擎再往下挪 5）
const SWAY = { 4: 5, 5: 5, 6: 5, 7: -5, 8: -5, 9: -5, 10: 5, 11: 5, 12: 5, 13: -5, 14: -5, 15: -5 };
const STEP = [4, 7, 10, 13, 16];                       // 晃的时候身子挪的那几帧
const JUMP = { 36: -10, 37: -20, 38: -10 };
const SQUASH = { 23: 5, 33: 5, 34: 5, 35: -5, 36: -5, 39: 10, 40: 5 };
// 牌面：K 是 ink 那圈边，G 是 signGreen 底。r = 5.5 格的圆，每行 5/7/9/11×5/9/7/5 格
const DISC = [
  '...KKKKK...',
  '..KGGGGGK..',
  '.KGGGGGGGK.',
  'KGGGGGGGGGK',
  'KGGGGGGGGGK',
  'KGGGGGGGGGK',
  'KGGGGGGGGGK',
  'KGGGGGGGGGK',
  '.KGGGGGGGK.',
  '..KGGGGGK..',
  '...KKKKK...'
];
// 白勾 7×6 格，画在牌面第 2–8 列、第 3–8 行；拐角那一行填实，70pt 下是一个粗粗的「✔」而不是两根分开的笔画
const CHECK = [
  '0000011',
  '0000111',
  '1001110',
  '1111100',
  '0111000',
  '0010000'
];
const only = (rows, ch) => rows.map(r => [...r].map(c => (c === ch ? '1' : '0')).join(''));
const RIM = only(DISC, 'K'), FACE = only(DISC, 'G');
const CHECK_PIXELS = CHECK.join('').match(/1/g).length * 25;                                             // 18 格 = 450
const SIGN_FRONT_PIXELS = DISC.join('').replace(/\./g, '').length * 25 - CHECK_PIXELS;                          // 97 格 − 勾盖住的 = 1975

module.exports = {
  id: 'sign-yes',
  label: '举✅牌',
  frames: 45,
  ms: [70, 60, 70],
  group: 'sticker',
  // 举着眨眼（表情包）/ 晃到右 / 晃到左 / 垂着 / 预备 / 一帧举起 / 蹦到顶冒星 / 落地压扁
  keyframes: [0, 4, 7, 23, 33, 35, 37, 39],
  // 表情包定帧是首帧：右上绿牌白勾、左眼眨着、左手「耶」、大金星
  stickerFrame: 0,

  // 这一支自己的亮绿，见开头 ①
  palette: { signGreen: '#3f9a4e' },

  pose(i) {
    const dx = SWAY[i] ?? 0, jump = JUMP[i] ?? 0;
    const squash = STEP.includes(i) ? -5 : SQUASH[i] ?? 0;
    const up = i >= 35 || i <= 21;
    // 举着的手跟着身子起落、压扁拉长（举高的手是挂在头顶那一截上的）；垂着的手只在预备那两帧自己往下沉
    const hy = up ? UP + jump + squash : i === 22 ? MID : i === 33 || i === 34 ? DIP : REST;
    // 帽子落后一帧：身子往哪边挪，帽子那一帧就留在反方向 5，下一帧扣回正中
    const prev = SWAY[i - 1] ?? 0, hatShift = STEP.includes(i) ? -5 * Math.sign(dx - prev) : 0;
    // 举着的手和帽子一起落后那一帧：手是举在檐右头外面的，身子挪了帽子还没跟上，手先挪过去就会压到帽子边上（睡帽的绒球）
    const hx = up ? HX + dx + hatShift : HX_LOW + dx;
    // 牌往哪边斜：往左晃的那两下，挪完的下一帧牌随势往左斜一格；放下来的帧往外斜一格，让开睡帽的绒球
    const tilt = !up ? 1 : dx < 0 && !STEP.includes(i) ? -1 : 0;
    // 左手：举牌的时候「耶」——往外上抬、歪 −15°；手不跟 dx / jump / squash，自己加
    const left = up ? { x: 75 + dx, y: 208 + jump + squash, a: -15 } : { x: 80, y: 218 + squash };
    // 眨眼从牌到位那一下（36）一直眨到晃完停住（19），36–37 蹦在空中两只眼都眯起来；31–32 垂着歇的时候普通地眨一下
    const wink = i >= 38 || i <= 19;
    const eyes = i === 36 || i === 37 || i === 31 || i === 32 ? 'closed' : wink ? ['closed', 'open'] : 'open';
    const look = i >= 33 && i <= 35 ? [5, -5] : i >= 26 && i <= 29 ? [5, 0] : [0, 0];
    const air = jump <= -10;
    const star = i === 36 || i === 2 || i === 3 ? 'sparkle' : i >= 37 || i <= 1 ? 'big' : null;
    return {
      dx, jump, squash, eyes, gazeX: look[0], gazeY: look[1], hatShift,
      hands: [left, { x: hx, y: hy }],
      // 空中四只脚收 5、往中间拢；落地那一帧放下来
      feet: air ? [5, 5, 5, 5] : [0, 0, 0, 0],
      footOffsets: air ? [5, 0, 0, -5] : [0, 0, 0, 0],
      // smile：这一帧闭着的眼补成「∩」（31–32 那下普通的眨眼不补，还是平的一道）
      tool: { sign: up ? 'up' : 'down', tilt, star, smile: !(i === 31 || i === 32) }
    };
  },

  // 牌的位置全从这一帧真画出来的右手算：举着时手左上角 (230, 185)，柄在 240–245×170–185、牌面 215–270×115–170、勾 225–260×130–160。
  // 斜（tilt ±1）的时候柄从手顶往上一格挪 5、斜成一道台阶，牌面整块横挪 10，勾跟着走，不转——像素的勾一转就碎了（和 ❌ 摇牌一个画法）。
  // 举着：柄和牌面在 props（手之上、脚之下），勾在 lettering；垂着：三样都画在 paper，藏到头和帽子后面
  paint(ctx, p) {
    const h = ctx.hands[1], up = p.tool.sign === 'up', tilt = p.tool.tilt || 0;
    const back = up ? ctx.props : ctx.paper, mark = up ? ctx.lettering : ctx.paper;
    for (let k = 0; k < 3; k++) back.rect(h.x + 10 + 5 * tilt * k, h.y - 5 * (k + 1), 5, 5, 'leatherLight', k ? null : 'handle');
    const x0 = h.x - 15 + 10 * tilt, y0 = h.y - 70;
    back.pattern(RIM, x0, y0, 'ink', 5, 'sign');
    back.pattern(FACE, x0, y0, 'signGreen', 5);
    mark.pattern(CHECK, x0 + 10, y0 + 15, 'earWhite', 5, 'check');
    // 笑眼：闭着的那只两头各往下补一格 ink，成「∩」；补的那两格要落在光着的脸上——身子压扁、脚会落进马甲那一行（底边往上 20）就不补
    if (p.tool.smile) ctx.eyes.forEach((e, n) => {
      const d = e.drawn;
      if (!d || e.kind !== 'closed' || d.y + 10 > ctx.bottom - 20) return;
      ctx.effects.rect(d.x - 5, d.y + 5, 5, 5, 'ink', `smile-${n + 1}-a`);
      ctx.effects.rect(d.x + 10, d.y + 5, 5, 5, 'ink', `smile-${n + 1}-b`);
    });
    // 星钉在空中不跟牌走：它是「叮」的那一下冒出来的，牌子蹦上蹦下它不跟着跳。
    // 用 gold 不用 goldLight：这颗星首帧就在，是表情包里那颗——贴到白底聊天、纸色浅底（paper）上，goldLight 几乎看不见；
    // 这一批另外几支（震惊的金线、疑惑的问号、捧心的小星、大笑捶地的星）也都是 gold，深底上 gold 照样亮
    if (p.tool.star === 'big') ctx.effects.pattern(ctx.shapes.star, 175, 120, 'gold', 5, 'star');
    if (p.tool.star === 'sparkle') ctx.effects.pattern(ctx.shapes.sparkle, 180, 125, 'gold', 5, 'star');
  },

  check: {
    // 这一支自己的三条：
    //   牌、勾、星一个像素都不压在帽子上——穿哪套衣服都一样（check-art --outfit 和 --preview --outfit 都跑这一条）；
    //   举着的那只右手也不压帽子：睡帽的绒球就吊在檐右头外面，手一挪过去就盖掉半颗（第一版晃到左边那几下盖掉 140 个像素）；
    //   举着的帧牌面和勾整块露着：牌面 97 格减去勾盖住的 18 格是 1975 个像素，勾 450 个像素
    verify(i, { layers, pose, shown }) {
      const out = [];
      for (let k = 3; k < layers.hat.length; k += 4) {
        if (layers.hat[k] && (layers.props[k] || layers.lettering[k] || layers.effects[k])) { out.push('牌子、勾或星压在帽子上了'); break; }
      }
      if (pose.tool.sign === 'up') {
        let n = 0;
        for (let k = 3; k < layers.hat.length; k += 4) if (layers.hat[k] && layers['hand-right'][k]) n++;
        if (n) out.push(`举牌的右手压在帽子上 ${n} 个像素`);
      }
      if (pose.tool.sign === 'up') {
        if (shown('sign') !== SIGN_FRONT_PIXELS) out.push(`举起来的牌面只露 ${shown('sign')}/${SIGN_FRONT_PIXELS} 个像素`);
        if (shown('check') !== CHECK_PIXELS) out.push(`勾只露 ${shown('check')}/${CHECK_PIXELS} 个像素`);
      }
      return out;
    }
  }
};
